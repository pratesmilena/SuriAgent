BEGIN;
CREATE TABLE IF NOT EXISTS public.escola_professor_disciplinas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo text NOT NULL UNIQUE,
    professor text NOT NULL CHECK (length(trim(professor)) > 0),
    disciplina text NOT NULL CHECK (length(trim(disciplina)) > 0),
    etapa text NOT NULL CHECK (etapa IN ('ENSINO_FUNDAMENTAL','ENSINO_MEDIO')),
    observacao text,
    fonte text,
    verificado_em date,
    confirmado boolean NOT NULL DEFAULT false,
    publicado boolean NOT NULL DEFAULT false,
    busca tsvector GENERATED ALWAYS AS (
        to_tsvector('portuguese', coalesce(professor,'') || ' ' || coalesce(disciplina,''))
    ) STORED,
    CONSTRAINT escola_professores_publicacao_revisada CHECK (
        NOT publicado OR (confirmado AND observacao IS NULL AND verificado_em IS NOT NULL AND length(trim(coalesce(fonte,''))) > 0)
    )
);
ALTER TABLE public.escola_professor_disciplinas ENABLE ROW LEVEL SECURITY;
GRANT USAGE ON SCHEMA public TO anon, authenticated;
REVOKE ALL PRIVILEGES ON public.escola_professor_disciplinas FROM anon, authenticated;
GRANT SELECT (id,codigo,professor,disciplina,etapa,fonte,verificado_em,confirmado,publicado,busca)
    ON public.escola_professor_disciplinas TO anon, authenticated;
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='public' AND tablename='escola_professor_disciplinas' AND policyname='suri_professores_publicados') THEN
        CREATE POLICY suri_professores_publicados ON public.escola_professor_disciplinas
            FOR SELECT TO anon, authenticated USING (publicado AND confirmado);
    END IF;
END $$;
CREATE INDEX IF NOT EXISTS escola_professores_busca_idx ON public.escola_professor_disciplinas USING gin(busca);
