-- Executar no SQL Editor do Supabase como administrador.
-- Adiciona duas tabelas; preserva conhecimentos e horario_aulatarde.
-- Não insere fatos, não publica conteúdo e não dá permissão de escrita ao site.
BEGIN;

CREATE TABLE IF NOT EXISTS public.escola_conteudos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria text NOT NULL CHECK (categoria IN ('historia','cursos','projetos','ambiente','espacos','faq')),
    slug text NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    titulo text NOT NULL CHECK (length(trim(titulo)) > 0),
    conteudo text NOT NULL DEFAULT '',
    fonte text,
    verificado_em date,
    publicado boolean NOT NULL DEFAULT false,
    criado_em timestamptz NOT NULL DEFAULT now(),
    busca tsvector GENERATED ALWAYS AS (
        to_tsvector('portuguese', coalesce(titulo,'') || ' ' || coalesce(conteudo,''))
    ) STORED,
    CONSTRAINT escola_conteudos_publicacao_revisada CHECK (
        NOT publicado OR (length(trim(conteudo)) > 0 AND length(trim(coalesce(fonte,''))) > 0 AND verificado_em IS NOT NULL)
    )
);
CREATE INDEX IF NOT EXISTS escola_conteudos_categoria_idx ON public.escola_conteudos(categoria) WHERE publicado;
CREATE INDEX IF NOT EXISTS escola_conteudos_busca_idx ON public.escola_conteudos USING gin(busca);

CREATE TABLE IF NOT EXISTS public.escola_eventos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug text NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    titulo text NOT NULL CHECK (length(trim(titulo)) > 0),
    conteudo text NOT NULL DEFAULT '',
    inicio timestamptz,
    fim timestamptz,
    local text,
    publico_alvo text,
    fonte text,
    verificado_em date,
    publicado boolean NOT NULL DEFAULT false,
    criado_em timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT escola_eventos_datas CHECK (fim IS NULL OR (inicio IS NOT NULL AND fim >= inicio)),
    CONSTRAINT escola_eventos_publicacao_revisada CHECK (
        NOT publicado OR (inicio IS NOT NULL AND length(trim(conteudo)) > 0 AND length(trim(coalesce(fonte,''))) > 0 AND verificado_em IS NOT NULL)
    )
);
CREATE INDEX IF NOT EXISTS escola_eventos_inicio_idx ON public.escola_eventos(inicio) WHERE publicado;

ALTER TABLE public.escola_conteudos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.escola_eventos ENABLE ROW LEVEL SECURITY;
GRANT USAGE ON SCHEMA public TO anon, authenticated;
REVOKE ALL PRIVILEGES ON public.escola_conteudos, public.escola_eventos FROM anon, authenticated;
GRANT SELECT (id,categoria,slug,titulo,conteudo,fonte,verificado_em,publicado,busca)
    ON public.escola_conteudos TO anon, authenticated;
GRANT SELECT (id,slug,titulo,conteudo,inicio,fim,local,publico_alvo,fonte,verificado_em,publicado)
    ON public.escola_eventos TO anon, authenticated;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='public' AND tablename='escola_conteudos' AND policyname='suri_conteudos_publicados') THEN
        CREATE POLICY suri_conteudos_publicados ON public.escola_conteudos
            FOR SELECT TO anon, authenticated USING (publicado = true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='public' AND tablename='escola_eventos' AND policyname='suri_eventos_publicados') THEN
        CREATE POLICY suri_eventos_publicados ON public.escola_eventos
            FOR SELECT TO anon, authenticated USING (publicado = true);
    END IF;
END $$;
COMMIT;
